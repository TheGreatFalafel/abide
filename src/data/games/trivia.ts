export function triviaForDifficulty(difficulty: GameDifficulty, count = 5): TriviaQuestion[] {
  const pool =
    difficulty === 'beginner'
      ? TRIVIA_BANK.filter((q) => q.difficulty === 'beginner')
      : difficulty === 'intermediate'
        ? TRIVIA_BANK.filter((q) => q.difficulty !== 'advanced')
        : TRIVIA_BANK
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length))
}
