function mc(
  id: string,
  prompt: string,
  choices: string[],
  answer: number,
  explanation: string,
  difficulty: CurriculumDifficulty,
): LanguageExercise {
  return {
    kind: 'mc',
    question: { id, type: 'mc', prompt, choices, answer, explanation, difficulty },
  }
}

